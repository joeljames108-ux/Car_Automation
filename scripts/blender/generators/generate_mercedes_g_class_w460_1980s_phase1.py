        p1 = Vector((x1, y1, z1))
        p2 = Vector((x2, y2, z2))
        v_damp = p2 - p1
        rot_damp = Vector((0, 0, 1)).rotation_difference(v_damp.normalized()).to_matrix().to_4x4()
