        stalk_base_f = Vector((side * 0.88, 0.48, 0.76))
        stalk_base_r = Vector((side * 0.89, 0.40, 0.76))

        # Mirror pod center: X = +/- 0.99m, Y = 0.42m, Z = 0.86m
        pod_center = Vector((side * 0.99, 0.42, 0.86))
        stalk_top_f = pod_center + Vector((side * -0.04,  0.03, -0.04))
        stalk_top_r = pod_center + Vector((side * -0.04, -0.03, -0.04))

        # 1. Dual Cantilever Support Stalks (Carbon-finished aerodynamic pylons)
        create_cylinder_between(bm_carbon, stalk_base_f, stalk_top_f, radius=0.008, segments=8)
        create_cylinder_between(bm_carbon, stalk_base_r, stalk_top_r, radius=0.007, segments=8)

