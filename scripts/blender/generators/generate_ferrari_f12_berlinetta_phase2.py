# 28. SUBSYSTEM 25: REAR DIFFUSER CENTRAL AERO STRAKES & VORTEX SHEDDERS
# ----------------------------------------------------------------------------
def build_f12_rear_diffuser_central_aero_strakes_and_vortex_shedders(parent, mats):
    """
    Constructs the central diffuser keel aerodynamic micro-channels,
    longitudinal vortex shedding serrations, and rear underbody splitters:
    Guides high-velocity underfloor air upwards into the low-pressure wake,
    preventing boundary layer separation under dynamic pitch.
    """
    bm_keel = bmesh.new()

    # Central Venturi Tunnels (Flanking the center rain lamp: X = +/- 0.06m)
    for side in [1.0, -1.0]:
        # Central Longitudinal Keel Fin
        keel_pts_top = [
            Vector((side * 0.055, -2.02, 0.225)),
            Vector((side * 0.055, -2.14, 0.215)),
            Vector((side * 0.055, -2.25, 0.205)),
        ]
        keel_pts_bot = [
            Vector((side * 0.055, -2.02, 0.125)),
            Vector((side * 0.055, -2.14, 0.145)),
            Vector((side * 0.055, -2.25, 0.165)),
        ]
        make_quad_strip(bm_keel, keel_pts_top if side > 0 else keel_pts_bot,
                                 keel_pts_bot if side > 0 else keel_pts_top)

        # Micro-Serrated Vortex Shedding Serrations along the fin bottom
        for s_idx in range(6):
            t_s = s_idx / 5.0
            p_edge = keel_pts_bot[0] * (1.0 - t_s) + keel_pts_bot[-1] * t_s
            p_notch = p_edge + Vector((0.0, 0.012, 0.008))
            create_cylinder_between(bm_keel, p_edge, p_notch, radius=0.002, segments=4)

        # Inboard Auxiliary Flap Airfoils
        flap_s = Vector((side * 0.055, -2.18, 0.185))
        flap_e = Vector((side * 0.095, -2.26, 0.195))
        create_oriented_box_between(bm_keel, flap_s, flap_e, width=0.004, height=0.018)

    mat_carbon = bpy.data.materials.get("F12_MAT_Twill_Gloss_Carbon") or mats["lamp_bucket"]
    return link_obj("GEO_F12_Diffuser_CentralKeelStrakes", bm_keel, parent, mat_carbon, bevel=0.001)

