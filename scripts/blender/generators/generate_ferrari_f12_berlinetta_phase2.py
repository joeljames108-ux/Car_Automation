# 15. SUBSYSTEM 12: QUAD INCONEL EXHAUST TIPS & ACOUSTIC RESONANCE LINERS
# ----------------------------------------------------------------------------
def build_f12_exhaust_acoustic_liners_and_valves(parent, mats):
    """
    Constructs the micro-detailed internal architecture of the quad Inconel exhaust pipes:
    - Double-walled rolled lips with thermal expansion annular airgap.
    - Perforated stainless steel internal acoustic resonator tubes.
    - Butterfly sound attenuation bypass valve discs and cross-shafts.
    - High-temperature matte carbon soot bore liners.
    """
    bm_liners = bmesh.new()
    bm_valves = bmesh.new()
    bm_soot   = bmesh.new()

    # Quad exhaust pipe coordinates (Bilateral dual tips):
    # Left Outer:  X = -0.74m, Y = -2.28m, Z = 0.22m
    # Left Inner:  X = -0.62m, Y = -2.28m, Z = 0.22m
    # Right Inner: X =  0.62m, Y = -2.28m, Z = 0.22m
    # Right Outer: X =  0.74m, Y = -2.28m, Z = 0.22m
    exhaust_positions = [
        Vector((-0.74, -2.28, 0.22)),
        Vector((-0.62, -2.28, 0.22)),
        Vector(( 0.62, -2.28, 0.22)),
        Vector(( 0.74, -2.28, 0.22)),
    ]

    pipe_r_outer = 0.052
    pipe_r_inner = 0.046
    pipe_r_core  = 0.040
    pipe_len     = 0.160

    for ep in exhaust_positions:
        # 1. Perforated Internal Acoustic Resonator Liner Tube
        res_res = bmesh.ops.create_cone(bm_liners, cap_ends=False, segments=24,
                                        radius1=pipe_r_inner, radius2=pipe_r_inner, depth=pipe_len)
        v_res = res_res['verts']
        bmesh.ops.rotate(bm_liners, verts=v_res, matrix=Matrix.Rotation(math.radians(90.0), 3, 'X'))
        bmesh.ops.translate(bm_liners, verts=v_res, vec=ep + Vector((0.0, 0.06, 0.0)))

        # Perforated Acoustic Sipe Ring Details (micro-grooves)
        for g_idx in range(5):
            g_y = ep.y + 0.02 + g_idx * 0.025
            res_grp = bmesh.ops.create_cone(bm_liners, cap_ends=False, segments=16,
                                            radius1=pipe_r_inner - 0.001, radius2=pipe_r_inner - 0.001, depth=0.004)
            v_grp = res_grp['verts']
            bmesh.ops.rotate(bm_liners, verts=v_grp, matrix=Matrix.Rotation(math.radians(90.0), 3, 'X'))
            bmesh.ops.translate(bm_liners, verts=v_grp, vec=Vector((ep.x, g_y, ep.z)))

        # 2. Butterfly Bypass Valve Disc & Transverse Pivot Shaft
        valve_pos = ep + Vector((0.0, 0.09, 0.0))
        # Pivot shaft
        create_cylinder_between(bm_valves, valve_pos - Vector((pipe_r_core, 0.0, 0.0)),
                                           valve_pos + Vector((pipe_r_core, 0.0, 0.0)),
                                radius=0.003, segments=6)
        # Valve Disc (Angled 28 degrees open in sport mode)
        res_disc = bmesh.ops.create_cone(bm_valves, cap_ends=True, segments=16, radius1=pipe_r_core, radius2=pipe_r_core, depth=0.003)
        v_disc = res_disc['verts']
        bmesh.ops.rotate(bm_valves, verts=v_disc, matrix=Matrix.Rotation(math.radians(28.0), 3, 'X'))
        bmesh.ops.rotate(bm_valves, verts=v_disc, matrix=Matrix.Rotation(math.radians(90.0), 3, 'X'))
        bmesh.ops.translate(bm_valves, verts=v_disc, vec=valve_pos)

        # 3. Inner Bore Carbon Soot Deposit Back-Plate
        res_soot = bmesh.ops.create_cone(bm_soot, cap_ends=True, segments=20, radius1=pipe_r_core, radius2=pipe_r_core, depth=0.010)
        v_soot = res_soot['verts']
        bmesh.ops.rotate(bm_soot, verts=v_soot, matrix=Matrix.Rotation(math.radians(90.0), 3, 'X'))
        bmesh.ops.translate(bm_soot, verts=v_soot, vec=ep + Vector((0.0, 0.14, 0.0)))

    obj_lin = link_obj("GEO_F12_Exhaust_AcousticResonatorLiners", bm_liners, parent, mats["chrome_jewelry"], bevel=0.001)
    obj_val = link_obj("GEO_F12_Exhaust_ButterflyBypassValves", bm_valves, parent, mats["titanium_fasteners"])
    obj_sot = link_obj("GEO_F12_Exhaust_CarbonSootBores", bm_soot, parent, mats["exhaust_soot"])

    return obj_lin, obj_val, obj_sot

