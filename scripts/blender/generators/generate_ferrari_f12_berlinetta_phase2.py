def set_pbr_socket(bsdf, names, value):
    """Safely sets a material input socket matching any candidate name."""
    for n in names:
        if n in bsdf.inputs:
            bsdf.inputs[n].default_value = value
            return

def make_pbr_material(name, base_color=(0.8, 0.8, 0.8, 1.0), metallic=0.0,
                      roughness=0.3, transmission=0.0, ior=1.50, clearcoat=0.0,
                      emission_color=(0.0, 0.0, 0.0, 1.0), emission_strength=0.0):
    """Creates a high-precision Principled BSDF PBR material."""
    mat = bpy.data.materials.get(name)
    if mat is None:
        mat = bpy.data.materials.new(name=name)
    mat.use_nodes = True
    nodes = mat.node_tree.nodes
    nodes.clear()

    out_node = nodes.new("ShaderNodeOutputMaterial")
    bsdf = nodes.new("ShaderNodeBsdfPrincipled")

    set_pbr_socket(bsdf, ["Base Color", "BaseColor"], base_color)
    set_pbr_socket(bsdf, ["Metallic"], metallic)
    set_pbr_socket(bsdf, ["Roughness"], roughness)
    set_pbr_socket(bsdf, ["Transmission", "Transmission Weight"], transmission)
    set_pbr_socket(bsdf, ["IOR"], ior)
    set_pbr_socket(bsdf, ["Coat Weight", "Clearcoat"], clearcoat)
    set_pbr_socket(bsdf, ["Coat Roughness", "Clearcoat Roughness"], 0.03)

    if emission_strength > 0.001:
        set_pbr_socket(bsdf, ["Emission Color", "Emission"], emission_color)
        set_pbr_socket(bsdf, ["Emission Strength"], emission_strength)

    mat.node_tree.links.new(bsdf.outputs["BSDF"], out_node.inputs["Surface"])
    return mat

