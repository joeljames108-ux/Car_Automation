# 10. SUBSYSTEM 7: SIGNATURE CIRCULAR OLED AFTERBURNER TAILLAMPS
# ----------------------------------------------------------------------------
def build_f12_circular_taillamp_assemblies(parent, mats):
    """
    Constructs the classic signature Ferrari circular OLED afterburner taillamps (L & R):
    - Outer stepped chrome circular bezel ring.
    - Deep anthracite internal bucket housing.
    - Outer 24-diode circular OLED red halo ring (position & brake lamp).
    - Central clear circular core with parabolic chrome reflector (reverse lamp).
    - Horizontal amber turn indicator LED strip bisecting the circular housing.
    - Ruby red outer polycarbonate lens with concentric circular Fresnel ridges.
    """
    bm_bezel  = bmesh.new()
    bm_bucket = bmesh.new()
    bm_halo   = bmesh.new()
    bm_revers = bmesh.new()
    bm_turn   = bmesh.new()
    bm_lens   = bmesh.new()

    for side in [1.0, -1.0]:
        # Center coordinates on rear transom: X = +/- 0.660m, Y = -2.302m, Z = 0.680m
        tail_center = Vector((side * 0.660, -2.302, 0.680))
        r_outer = 0.088
        r_halo  = 0.072
        r_core  = 0.042

        # 1. Outer Stepped Chrome Bezel Ring
        res_bez = bmesh.ops.create_cone(bm_bezel, cap_ends=True, segments=32, radius1=r_outer, radius2=r_outer, depth=0.016)
        v_bez = res_bez['verts']
        bmesh.ops.rotate(bm_bezel, verts=v_bez, matrix=Matrix.Rotation(math.radians(90.0), 3, 'X'))
        bmesh.ops.translate(bm_bezel, verts=v_bez, vec=tail_center)

        # 2. Deep Anthracite Internal Bucket Cylinder
        res_bkt = bmesh.ops.create_cone(bm_bucket, cap_ends=True, segments=32, radius1=r_outer - 0.005, radius2=r_outer - 0.012, depth=0.045)
        v_bkt = res_bkt['verts']
        bmesh.ops.rotate(bm_bucket, verts=v_bkt, matrix=Matrix.Rotation(math.radians(90.0), 3, 'X'))
        bmesh.ops.translate(bm_bucket, verts=v_bkt, vec=tail_center + Vector((0.0, 0.020, 0.0)))

        # 3. Outer Circular 24-Diode OLED Red Halo Ring
        num_halo_diodes = 24
        for d_i in range(num_halo_diodes):
            ang = 2.0 * math.pi * d_i / num_halo_diodes
            dx = r_halo * math.cos(ang)
            dz = r_halo * math.sin(ang)
            diode_pos = tail_center + Vector((dx, -0.004, dz))

            res_d = bmesh.ops.create_cube(bm_halo, size=1.0)
            bmesh.ops.scale(bm_halo, verts=res_d['verts'], vec=(0.010, 0.006, 0.010))
            bmesh.ops.translate(bm_halo, verts=res_d['verts'], vec=diode_pos)

        # Continuous Circular Emissive Light-Guide Ring beneath the diodes
        res_hring = bmesh.ops.create_cone(bm_halo, cap_ends=True, segments=32, radius1=r_halo + 0.006, radius2=r_halo - 0.006, depth=0.008)
        v_hr = res_hring['verts']
        bmesh.ops.rotate(bm_halo, verts=v_hr, matrix=Matrix.Rotation(math.radians(90.0), 3, 'X'))
        bmesh.ops.translate(bm_halo, verts=v_hr, vec=tail_center + Vector((0.0, 0.005, 0.0)))

        # 4. Central Circular Reverse Lamp Optic & Parabolic Reflector
        res_rev = bmesh.ops.create_cone(bm_revers, cap_ends=True, segments=24, radius1=r_core, radius2=0.015, depth=0.028)
        v_rev = res_rev['verts']
        bmesh.ops.rotate(bm_revers, verts=v_rev, matrix=Matrix.Rotation(math.radians(90.0), 3, 'X'))
        bmesh.ops.translate(bm_revers, verts=v_rev, vec=tail_center + Vector((0.0, 0.016, 0.0)))

        # Center Reverse LED Emitter
        res_rled = bmesh.ops.create_cone(bm_revers, cap_ends=True, segments=12, radius1=0.008, radius2=0.008, depth=0.012)
        v_rled = res_rled['verts']
        bmesh.ops.rotate(bm_revers, verts=v_rled, matrix=Matrix.Rotation(math.radians(90.0), 3, 'X'))
        bmesh.ops.translate(bm_revers, verts=v_rled, vec=tail_center + Vector((0.0, 0.008, 0.0)))

        # 5. Horizontal Amber Turn Indicator LED Bar (Bisecting center of housing)
        bar_p1 = tail_center + Vector((-r_outer * 0.85, -0.006, 0.0))
        bar_p2 = tail_center + Vector(( r_outer * 0.85, -0.006, 0.0))
        create_oriented_box_between(bm_turn, bar_p1, bar_p2, width=0.006, height=0.012)

        # 6. Ruby Red Outer Polycarbonate Lens Cover with Fresnel Ridges
        res_l = bmesh.ops.create_cone(bm_lens, cap_ends=True, segments=32, radius1=r_outer - 0.002, radius2=r_outer - 0.002, depth=0.008)
        v_l = res_l['verts']
        bmesh.ops.rotate(bm_lens, verts=v_l, matrix=Matrix.Rotation(math.radians(90.0), 3, 'X'))
        bmesh.ops.translate(bm_lens, verts=v_l, vec=tail_center - Vector((0.0, 0.008, 0.0)))

        # Concentric Fresnel Groove Rings
        for f_rad in [0.030, 0.055, 0.078]:
            res_fr = bmesh.ops.create_cone(bm_lens, cap_ends=True, segments=24, radius1=f_rad + 0.002, radius2=f_rad - 0.002, depth=0.003)
            v_fr = res_fr['verts']
            bmesh.ops.rotate(bm_lens, verts=v_fr, matrix=Matrix.Rotation(math.radians(90.0), 3, 'X'))
            bmesh.ops.translate(bm_lens, verts=v_fr, vec=tail_center - Vector((0.0, 0.011, 0.0)))

    obj_b = link_obj("GEO_F12_Taillamp_ChromeBezelRings", bm_bezel, parent, mats["chrome_jewelry"], bevel=0.001)
    obj_k = link_obj("GEO_F12_Taillamp_AnthraciteBuckets", bm_bucket, parent, mats["lamp_bucket"], bevel=0.001)
    obj_h = link_obj("GEO_F12_Taillamp_OLED_HaloDiodes", bm_halo, parent, mats["oled_halo_red"])
    obj_r = link_obj("GEO_F12_Taillamp_ReverseReflectorOptics", bm_revers, parent, mats["reverse_lamp_clear"])
    obj_t = link_obj("GEO_F12_Taillamp_AmberTurnBars", bm_turn, parent, mats["led_indicator_amber"])
    obj_l = link_obj("GEO_F12_Taillamp_RubyFresnelLenses", bm_lens, parent, mats["taillamp_ruby_lens"])

    return obj_b, obj_k, obj_h, obj_r, obj_t, obj_l

