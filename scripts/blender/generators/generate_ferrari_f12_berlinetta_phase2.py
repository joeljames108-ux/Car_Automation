    obj_am = link_obj("GEO_F12_SideMirror_AmberSignals", bm_amber, parent, mats["led_indicator_amber"])
    obj_cb = link_obj("GEO_F12_SideMirror_StalksAndBezels", bm_carbon, parent, mats["lamp_bucket"], bevel=0.001)

