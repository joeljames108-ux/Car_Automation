    # 1. Formula 1 Central Rain / Fog Lamp: X = 0.000m, Y = -2.260m, Z = 0.190m
    rain_pos = Vector((0.000, -2.260, 0.190))

    # Chrome Reflector Pocket Box
    res_box = bmesh.ops.create_cube(bm_chrome, size=1.0)
