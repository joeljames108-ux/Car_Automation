    v_cam = res_cam['verts']
    bmesh.ops.rotate(bm_plate, verts=v_cam, matrix=Matrix.Rotation(math.radians(-30.0), 3, 'X'))
    bmesh.ops.translate(bm_plate, verts=v_cam, vec=cam_pos)

    obj_rn = link_obj("GEO_F12_F1_DiffuserRainLamp", bm_rain, parent, mats["f1_rain_lamp_led"])
    obj_ch = link_obj("GEO_F12_RainLamp_ChromeHousing", bm_chrome, parent, mats["chrome_jewelry"], bevel=0.001)
    obj_rf = link_obj("GEO_F12_RearReflex_Reflectors", bm_reflex, parent, mats["reflex_reflector_red"])
    obj_pl = link_obj("GEO_F12_LicensePlate_LampsAndCam", bm_plate, parent, mats["lamp_bucket"], bevel=0.001)

    return obj_rn, obj_ch, obj_rf, obj_pl

