    exterior_objs.extend(gh_objs)

    print("[4/5] Assembling dual kidney grille, Angel Eyes optics & xenon headlamps...")
    light_objs = build_x5_front_fascia_and_lighting(mats)
    exterior_objs.extend(light_objs)

