        # 2. 16x8" Satin Silver Moab 5-Spoke Cast Alloy Wheel Rim
        mat_rim = Matrix.Translation(center) @ rot_y
        _compat_create_cylinder(bm_moab, radius=0.215, depth=0.20, segments=24, matrix=mat_rim)

