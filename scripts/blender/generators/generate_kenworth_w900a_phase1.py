# 23. SUBSYSTEM 20: FIFTH-WHEEL APPROACH RAMPS & FRAME DECK CATWALK
# ----------------------------------------------------------------------------
def build_fifth_wheel_deck_catwalk_base(parent, mats):
    """
    Constructs the heavy aluminum diamond-plate chassis catwalk & frame approach ramps:
    - Diamond-plate center walkway behind cab for driver trailer hookup safety
    - Angled steel trailer approach ramps on rear frame horns (preventing kingpin gouging)
    - Paved frame rail filler deck plates between tandem drive axles
    """
    bm_deck = bmesh.new()
    bm_ramps = bmesh.new()

    # 1. Diamond-Plate Center Catwalk Deck (From Sleeper Rear Y=-0.95 to Bogie Front Y=-1.70)
    cat_y_start = -0.980
    cat_y_end   = -1.680
    cat_mid_y   = (cat_y_start + cat_y_end) * 0.5
    cat_len     = cat_y_start - cat_y_end
    cat_w       =  0.860
    cat_z       =  0.935

    res_cat = bmesh.ops.create_cube(bm_deck, size=1.0)
    bmesh.ops.scale(bm_deck, verts=res_cat['verts'], vec=(cat_w, cat_len, 0.018))
    bmesh.ops.translate(bm_deck, verts=res_cat['verts'], vec=Vector((0.0, cat_mid_y, cat_z)))

    # Perimeter Structural Angle Stiffeners
    for side in [1.0, -1.0]:
        p_st1 = Vector((side * (cat_w * 0.5), cat_y_start, cat_z - 0.015))
        p_st2 = Vector((side * (cat_w * 0.5), cat_y_end,   cat_z - 0.015))
        create_oriented_box_between(bm_deck, p_st1, p_st2, width=0.025, height=0.035)

    # 2. Rear Frame Trailer Approach Ramps (Angled downward on both frame rails at Y=-4.15m to -4.30m)
    for side in [1.0, -1.0]:
        rx = side * 0.470
        p_ramp_top = Vector((rx, -4.100, 0.920))
        p_ramp_bot = Vector((rx, -4.300, 0.760))
        create_oriented_box_between(bm_ramps, p_ramp_top, p_ramp_bot, width=0.090, height=0.025)

        # Gusset stiffener under approach ramp
        p_gus_top = (p_ramp_top + p_ramp_bot) * 0.5
        p_gus_bot = Vector((rx, -4.200, 0.720))
        create_oriented_box_between(bm_ramps, p_gus_top, p_gus_bot, width=0.018, height=0.080)

    obj_deck  = link_obj("CHASSIS_Center_Catwalk_Deck", bm_deck, parent, mats['polished_aluminum'], bevel=0.002)
    obj_ramps = link_obj("CHASSIS_Trailer_Approach_Ramps", bm_ramps, parent, mats['chassis_black'], bevel=0.003)

    return [obj_deck, obj_ramps]

