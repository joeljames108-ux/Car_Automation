# 22. SUBSYSTEM 19: CAB ENTRY GRAB HANDLES, FENDER SHIELDS & HOOD STOPS
# ----------------------------------------------------------------------------
def build_cab_entry_assist_grab_handles_and_fender_guards(parent, mats):
    """
    Constructs the exterior stainless/chrome driver entry grab rails & fender shields:
    - 36-inch vertical polished stainless steel grab handles on cab B-pillars (left and right)
    - Lower dog-leg entry grab rails mounted on battery and tool box steps
    - Heavy molded rubber fender stone guards / gravel deflectors behind front steer tires
    - Heavy stamped steel hood guide locator cones and rubber rest bumpers
    """
    bm_rails  = bmesh.new()
    bm_rubber = bmesh.new()

    for side in [1.0, -1.0]:
        sx = side * 1.095  # Outer cab wall

        # 1. Main 36-Inch Vertical Polished Cab B-Pillar Grab Handle
        p_gh_top = Vector((sx + side * 0.045, 0.050, 1.950))
        p_gh_bot = Vector((sx + side * 0.045, 0.050, 1.050))
        create_cylinder_between(bm_rails, p_gh_top, p_gh_bot, radius=0.014, segments=12)

        # Upper and Lower Standoff Stems to Cab Body
        for stem_p in [p_gh_top, p_gh_bot]:
            p_cab_flange = Vector((sx, 0.050, stem_p.z))
            create_cylinder_between(bm_rails, stem_p, p_cab_flange, radius=0.016, segments=10)
            # 3-bolt diamond mounting flange
            res_fl = bmesh.ops.create_cone(bm_rails, cap_ends=True, segments=10,
                                           radius1=0.035, radius2=0.035, depth=0.008)
            v_fl = res_fl['verts']
            bmesh.ops.rotate(bm_rails, verts=v_fl, matrix=Matrix.Rotation(math.radians(90.0), 3, 'Y'))
            bmesh.ops.translate(bm_rails, verts=v_fl, vec=p_cab_flange)

        # 2. Lower Dog-Leg Entry Grab Rail on Battery/Tool Box Deck
        p_dl_top = Vector((side * 0.980, 1.250, 1.080))
        p_dl_mid = Vector((side * 0.980, 1.350, 0.880))
        p_dl_bot = Vector((side * 0.980, 1.480, 0.780))
        create_cylinder_between(bm_rails, p_dl_top, p_dl_mid, radius=0.012, segments=10)
        create_cylinder_between(bm_rails, p_dl_mid, p_dl_bot, radius=0.012, segments=10)

        # 3. Heavy Rubber Fender Stone Guards / Gravel Deflectors (Behind Steer Tires)
        sg_y = 1.780
        sg_z = 0.580
        sg_x = side * 1.150
        res_sg = bmesh.ops.create_cube(bm_rubber, size=1.0)
        bmesh.ops.scale(bm_rubber, verts=res_sg['verts'], vec=(0.140, 0.014, 0.280))
        bmesh.ops.translate(bm_rubber, verts=res_sg['verts'], vec=Vector((sg_x, sg_y, sg_z)))

        # Top mounting steel clamp strip with 3 bolts
        p_strip1 = Vector((sg_x - side * 0.06, sg_y + 0.010, sg_z + 0.130))
        p_strip2 = Vector((sg_x + side * 0.06, sg_y + 0.010, sg_z + 0.130))
        create_oriented_box_between(bm_rails, p_strip1, p_strip2, width=0.010, height=0.025)
        for bi in [-0.04, 0.0, 0.04]:
            add_hex_bolt(bm_rails, Vector((sg_x + side * bi, sg_y + 0.016, sg_z + 0.130)),
                         direction=Vector((0, 1, 0)), radius=0.005, height=0.008)

        # 4. Hood Guide Alignment Cones & Frame Rest Bumpers
        cone_pos = Vector((side * 0.440, 1.420, 1.040))
        res_cone = bmesh.ops.create_cone(bm_rubber, cap_ends=True, segments=12,
                                         radius1=0.030, radius2=0.010, depth=0.060)
        bmesh.ops.translate(bm_rubber, verts=res_cone['verts'], vec=cone_pos)

    obj_rails  = link_obj("HARDWARE_Cab_Grab_Rails_And_Strips", bm_rails, parent, mats['chrome'], bevel=0.001)
    obj_rubber = link_obj("BODY_Fender_Stone_Guards", bm_rubber, parent, mats['tire_rubber'], bevel=0.002)

    return [obj_rails, obj_rubber]

