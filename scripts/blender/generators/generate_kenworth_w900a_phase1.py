# 8. SUBSYSTEM 5: HOLLAND 3500 CAST STEEL SLIDING FIFTH-WHEEL COUPLING
# ----------------------------------------------------------------------------
def build_fifth_wheel_coupling(parent, mats):
    """
    Constructs the Holland 3500 heavy-duty cast steel fifth-wheel coupling:
    - Cast top plate with kingpin throat entry ramps and locking jaw pocket
    - Left-side manual pull release handle with forged rod and safety catch
    - Dual rocking trunnion pivots mounted on toothed slider rails
    - Pneumatic slider lock cylinder and high-pressure airline
    """
    bm_fw = bmesh.new()

    fw_y = -3.000  # Centered directly over tandem bogie center trunnion
    fw_z =  1.060  # Operating height above chassis frame rails

    # 1. Cast Steel Top Plate (Horseshoe shape with rearward entry throat)
    plate_pts = [
        Vector((-0.460, fw_y + 0.420, fw_z)),
        Vector(( 0.460, fw_y + 0.420, fw_z)),
        Vector(( 0.480, fw_y - 0.220, fw_z)),
        Vector(( 0.320, fw_y - 0.520, fw_z - 0.050)), # Right throat ramp
        Vector(( 0.090, fw_y - 0.180, fw_z)),         # Throat inner right
        Vector((-0.090, fw_y - 0.180, fw_z)),         # Throat inner left
        Vector((-0.320, fw_y - 0.520, fw_z - 0.050)), # Left throat ramp
        Vector((-0.480, fw_y - 0.220, fw_z)),
    ]
    # Loft top and bottom surfaces of fifth wheel plate
    plate_verts_top = [bm_fw.verts.new(p) for p in plate_pts]
    plate_verts_bot = [bm_fw.verts.new(p - Vector((0, 0, 0.045))) for p in plate_pts]

    # Create perimeter band
    n_pts = len(plate_pts)
    for i in range(n_pts):
        next_i = (i + 1) % n_pts
        bm_fw.faces.new((plate_verts_top[i], plate_verts_top[next_i],
                         plate_verts_bot[next_i], plate_verts_bot[i]))

    # Top surface n-gon
    try:
        bm_fw.faces.new(plate_verts_top)
        bm_fw.faces.new(list(reversed(plate_verts_bot)))
    except Exception:
        pass

    # Kingpin Jaw Pocket & Hardened Wear Ring
    p_jaw1 = Vector((0, fw_y - 0.05, fw_z - 0.05))
    p_jaw2 = Vector((0, fw_y - 0.05, fw_z + 0.01))
    create_cylinder_between(bm_fw, p_jaw1, p_jaw2, radius=0.080, segments=16)

    # 2. Left and Right Rocking Trunnion Pivot Brackets
    for side in [1.0, -1.0]:
        tx = side * 0.360
        # Pivot shaft
        p_piv1 = Vector((tx - 0.05, fw_y, fw_z - 0.040))
        p_piv2 = Vector((tx + 0.05, fw_y, fw_z - 0.040))
        create_cylinder_between(bm_fw, p_piv1, p_piv2, radius=0.035, segments=12)

        # Cast pedestal base tower
        p_ped_top = Vector((tx, fw_y, fw_z - 0.040))
        p_ped_bot = Vector((tx, fw_y, 0.940))
        create_oriented_box_between(bm_fw, p_ped_top, p_ped_bot, width=0.080, height=0.220)

    # 3. Toothed Slider Mounting Base Rails (Allowing fifth wheel fore/aft adjustment)
    for side in [1.0, -1.0]:
        sx = side * 0.440
        # Longitudinal slide rack bar
        p_sr1 = Vector((sx, fw_y + 0.700, 0.940))
        p_sr2 = Vector((sx, fw_y - 0.700, 0.940))
        create_oriented_box_between(bm_fw, p_sr1, p_sr2, width=0.045, height=0.040)

        # 16 Heavy Slide Rack Teeth along rail
        for ti in range(16):
            ty = fw_y + 0.600 - (ti * 0.080)
            p_tooth = Vector((sx, ty, 0.965))
            res_t = bmesh.ops.create_cube(bm_fw, size=1.0)
            bmesh.ops.scale(bm_fw, verts=res_t['verts'], vec=(0.048, 0.035, 0.020))
            bmesh.ops.translate(bm_fw, verts=res_t['verts'], vec=p_tooth)

    # 4. Manual Release Pull Rod Handle on Driver Side
    p_handle_jaw  = Vector((-0.100, fw_y - 0.05, fw_z - 0.02))
    p_handle_loop = Vector((-0.680, fw_y - 0.05, fw_z - 0.02))
    create_cylinder_between(bm_fw, p_handle_jaw, p_handle_loop, radius=0.009, segments=8)

    # Forged finger pull loop at end of handle
    res_loop = bmesh.ops.create_cone(bm_fw, cap_ends=True, segments=10, radius1=0.035, radius2=0.035, depth=0.012)
    v_loop = res_loop['verts']
    bmesh.ops.rotate(bm_fw, verts=v_loop, matrix=Matrix.Rotation(math.radians(90.0), 3, 'X'))
    bmesh.ops.translate(bm_fw, verts=v_loop, vec=p_handle_loop - Vector((0.02, 0, 0)))

    # Pneumatic Slider Release Cylinder
    p_cyl1 = Vector((0.0, fw_y + 0.150, 0.960))
    p_cyl2 = Vector((0.0, fw_y - 0.150, 0.960))
    create_cylinder_between(bm_fw, p_cyl1, p_cyl2, radius=0.032, segments=12)

    return link_obj("HARDWARE_Holland_3500_Fifth_Wheel", bm_fw, parent, mats['cast_iron'], bevel=0.003)

