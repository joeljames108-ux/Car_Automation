# 7. SUBSYSTEM 4: COMPLETE 10-WHEEL FLEET, ALCOA FORGED RIMS & 11R24.5 TIRES
# ----------------------------------------------------------------------------
def build_ten_wheel_fleet(parent, mats):
    """
    Constructs the full 10-wheel Class 8 fleet:
    - 2x Steer Axle Wheels: Alcoa 24.5" x 8.25" forged aluminum wheels (Convex outer offset)
    - 8x Drive Tandem Wheels: 4 dual wheel pairs (Concave deep-dish outer offset)
    - 10 authentic Alcoa hand holes with chamfered CNC machined edge lips
    - Commercial 11R24.5 tires (Steer: 5-rib highway tread; Drive: deep-lug cross traction blocks)
    - Recessed hex lug nuts (10 per wheel) and Kenworth chrome center hub caps
    """
    bm_rims  = bmesh.new()
    bm_tires = bmesh.new()
    bm_hubs  = bmesh.new()

    rim_dia     = 0.622  # 24.5 inches diameter = ~622 mm
    tire_dia    = 1.100  # 11R24.5 rolling diameter = ~1,100 mm (radius = 0.550 m)
    tire_w      = 0.280  # Section width 280 mm
    hub_bolt_r  = 0.143  # 10-bolt circle radius (285.75 mm BCD)

    # Fleet Wheel Locations: (Name, X, Y, Z, is_steer, is_dual_inner)
    wheel_instances = [
        # Front Steer Axle (Y = +2.600 m, Track = 2.080 m)
        ("Steer_L", -1.040,  2.600, 0.560, True, False),
        ("Steer_R",  1.040,  2.600, 0.560, True, False),

        # Forward Tandem Drive Axle (Y = -2.350 m, Dual track: Inner=0.92m, Outer=1.225m)
        ("Drive_Fwd_Outer_L", -1.225, -2.350, 0.560, False, False),
        ("Drive_Fwd_Inner_L", -0.920, -2.350, 0.560, False, True),
        ("Drive_Fwd_Inner_R",  0.920, -2.350, 0.560, False, True),
        ("Drive_Fwd_Outer_R",  1.225, -2.350, 0.560, False, False),

        # Rearward Tandem Drive Axle (Y = -3.650 m, Dual track: Inner=0.92m, Outer=1.225m)
        ("Drive_Rear_Outer_L", -1.225, -3.650, 0.560, False, False),
        ("Drive_Rear_Inner_L", -0.920, -3.650, 0.560, False, True),
        ("Drive_Rear_Inner_R",  0.920, -3.650, 0.560, False, True),
        ("Drive_Rear_Outer_R",  1.225, -3.650, 0.560, False, False),
    ]

    for w_name, wx, wy, wz, is_steer, is_inner in wheel_instances:
        facing_dir = -1.0 if wx < 0 else 1.0
        w_center = Vector((wx, wy, wz))

        # --------------------------------------------------------------------
        # A. Alcoa 24.5" Forged Aluminum Wheel Rim
        # --------------------------------------------------------------------
        rim_outer_lip = w_center + Vector((facing_dir * (tire_w * 0.45), 0, 0))
        rim_inner_lip = w_center - Vector((facing_dir * (tire_w * 0.45), 0, 0))

        # Outer stepped rim barrel
        create_cylinder_between(bm_rims, rim_inner_lip, rim_outer_lip, radius=rim_dia * 0.5, segments=28)
        # Dropped center well
        create_cylinder_between(bm_rims, rim_inner_lip, rim_outer_lip, radius=rim_dia * 0.44, segments=28)

        # Disc Face: Steer has convex outward dish; Drive has deep concave dish
        disc_offset = 0.050 if is_steer else -0.090
        disc_center = w_center + Vector((facing_dir * disc_offset, 0, 0))

        # Disc Hub Mounting Flange Plate
        p_disc_in  = disc_center - Vector((facing_dir * 0.015, 0, 0))
        p_disc_out = disc_center + Vector((facing_dir * 0.015, 0, 0))
        create_cylinder_between(bm_rims, p_disc_in, p_disc_out, radius=rim_dia * 0.46, segments=28)

        # 10 Iconic Alcoa Hand Holes (CNC-milled oval vent openings)
        for h_idx in range(10):
            h_angle = h_idx * (2.0 * math.pi / 10.0)
            h_rad   = rim_dia * 0.35
            h_pos   = disc_center + Vector((0, h_rad * math.cos(h_angle), h_rad * math.sin(h_angle)))
            # Chamfered hole boss
            p_h1 = h_pos - Vector((facing_dir * 0.018, 0, 0))
            p_h2 = h_pos + Vector((facing_dir * 0.018, 0, 0))
            create_cylinder_between(bm_rims, p_h1, p_h2, radius=0.038, segments=12)

        # 10 Recessed Hex Lug Nuts on 285.75mm Bolt Circle
        for l_idx in range(10):
            l_angle = l_idx * (2.0 * math.pi / 10.0) + (math.pi / 10.0)
            lx = disc_center.x + facing_dir * 0.018
            ly = disc_center.y + hub_bolt_r * math.cos(l_angle)
            lz = disc_center.z + hub_bolt_r * math.sin(l_angle)
            add_hex_bolt(bm_hubs, Vector((lx, ly, lz)), direction=Vector((facing_dir, 0, 0)),
                         radius=0.014, height=0.018)

        # Chrome Hub Cap
        if not is_inner:
            if is_steer:
                # Kenworth Chrome Bullet Dome Steer Hub Cap
                cap_pos = disc_center + Vector((facing_dir * 0.030, 0, 0))
                res_cap = bmesh.ops.create_icosphere(bm_hubs, subdivisions=2, radius=0.095)
                v_cap = res_cap['verts']
                bmesh.ops.scale(bm_hubs, verts=v_cap, vec=(0.45, 1.0, 1.0))
                bmesh.ops.translate(bm_hubs, verts=v_cap, vec=cap_pos)
            else:
                # Drive Axle Cylindrical Flange Hub with Axle Shaft Studs
                cap_pos = disc_center + Vector((facing_dir * 0.040, 0, 0))
                p_c1 = cap_pos - Vector((facing_dir * 0.035, 0, 0))
                p_c2 = cap_pos + Vector((facing_dir * 0.035, 0, 0))
                create_cylinder_between(bm_hubs, p_c1, p_c2, radius=0.105, segments=18)
                # 8 axle drive flange studs
                for as_i in range(8):
                    as_ang = as_i * (2.0 * math.pi / 8.0)
                    as_y = cap_pos.y + 0.082 * math.cos(as_ang)
                    as_z = cap_pos.z + 0.082 * math.sin(as_ang)
                    add_hex_bolt(bm_hubs, Vector((cap_pos.x + facing_dir * 0.038, as_y, as_z)),
                                 direction=Vector((facing_dir, 0, 0)), radius=0.009, height=0.010)

        # Brass Valve Stem with Knurled Cap
        vs_pos = disc_center + Vector((facing_dir * 0.040, 0.220, 0.0))
        p_vs1 = vs_pos
        p_vs2 = vs_pos + Vector((facing_dir * 0.035, -0.015, 0.0))
        create_cylinder_between(bm_rims, p_vs1, p_vs2, radius=0.006, segments=8)

        # --------------------------------------------------------------------
        # B. 11R24.5 Commercial Truck Tire Geometry
        # --------------------------------------------------------------------
        # Outer cylindrical tread band (cap_ends=False so wheel center is open)
        res_tire = bmesh.ops.create_cone(bm_tires, cap_ends=False, segments=32,
                                         radius1=tire_dia * 0.5, radius2=tire_dia * 0.5, depth=tire_w)
        v_tire = res_tire['verts']
        bmesh.ops.rotate(bm_tires, verts=v_tire, matrix=Matrix.Rotation(math.radians(90.0), 3, 'Y'))
        bmesh.ops.translate(bm_tires, verts=v_tire, vec=w_center)

        # Curved outer and inner annular sidewall rings (bridging tread to rim bead)
        for sw_dir in [1.0, -1.0]:
            pts_outer_ring = []
            pts_inner_ring = []
            for seg_i in range(32):
                ang = seg_i * (2.0 * math.pi / 32.0)
                cy = w_center.y + (tire_dia * 0.5) * math.cos(ang)
                cz = w_center.z + (tire_dia * 0.5) * math.sin(ang)
                pts_outer_ring.append(Vector((w_center.x + sw_dir * (tire_w * 0.5), cy, cz)))

                by = w_center.y + (rim_dia * 0.502) * math.cos(ang)
                bz = w_center.z + (rim_dia * 0.502) * math.sin(ang)
                pts_inner_ring.append(Vector((w_center.x + sw_dir * (tire_w * 0.42), by, bz)))

            v_out = [bm_tires.verts.new(p) for p in pts_outer_ring]
            v_in  = [bm_tires.verts.new(p) for p in pts_inner_ring]
            for si in range(32):
                next_si = (si + 1) % 32
                if sw_dir > 0:
                    try:
                        bm_tires.faces.new((v_out[si], v_out[next_si], v_in[next_si], v_in[si]))
                    except Exception:
                        pass
                else:
                    try:
                        bm_tires.faces.new((v_out[next_si], v_out[si], v_in[si], v_in[next_si]))
                    except Exception:
                        pass

        # Tire Tread Pattern
        if is_steer:
            # 5 Circumferential Highway Rib Grooves
            for rib_idx in [-0.09, -0.045, 0.0, 0.045, 0.09]:
                p_r1 = w_center + Vector((rib_idx - 0.008, 0, 0))
                p_r2 = w_center + Vector((rib_idx + 0.008, 0, 0))
                create_cylinder_between(bm_tires, p_r1, p_r2, radius=tire_dia * 0.505, segments=32)
        else:
            # Deep-Lug Cross Traction Cleats (Every 15 degrees around tire circumference)
            for lug_i in range(24):
                lug_ang = lug_i * (2.0 * math.pi / 24.0)
                lug_rad = tire_dia * 0.502
                ly = w_center.y + lug_rad * math.cos(lug_ang)
                lz = w_center.z + lug_rad * math.sin(lug_ang)
                # Outer lug block
                p_lug_l = Vector((w_center.x - tire_w * 0.42, ly, lz))
                p_lug_r = Vector((w_center.x + tire_w * 0.42, ly, lz))
                create_oriented_box_between(bm_tires, p_lug_l, p_lug_r, width=0.025, height=0.014)

    obj_rims  = link_obj("WHEEL_Alcoa_24_5_Forged_Rims", bm_rims, parent, mats['polished_aluminum'], bevel=0.002)
    obj_tires = link_obj("WHEEL_Commercial_11R24_5_Tires", bm_tires, parent, mats['tire_rubber'], bevel=0.003)
    obj_hubs  = link_obj("WHEEL_Chrome_Lug_Nuts_And_Hub_Caps", bm_hubs, parent, mats['chrome'], bevel=0.001)

    return [obj_rims, obj_tires, obj_hubs]

