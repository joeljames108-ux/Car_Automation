# 9. SUBSYSTEM 6: CONVENTIONAL 2.4-METER LONG BUTTERFLY HOOD & FENDER ARCHES
# ----------------------------------------------------------------------------
def build_conventional_long_hood(parent, mats):
    """
    Constructs the iconic 2.4-meter long Kenworth W900A conventional hood:
    - Massive long-nose fiberglass hood extending from cab cowl (Y=+1.40m) to grille (Y=+3.80m)
    - Full-length center longitudinal piano hinge spine with chrome hinge rod
    - Broad sweeping front fender arches with rolled wheel lip over steer tires
    - 24 stamped side engine cooling louvers per side with accurate airflow pitch
    - Heavy-duty rubber dog-bone hood hold-down latches with cast chrome catches
    """
    bm_hood    = bmesh.new()
    bm_fenders = bmesh.new()
    bm_louvers = bmesh.new()

    # Telemetry
    y_cowl   = 1.400
    y_grille = 3.800
    cowl_w   = 1.050  # Semi-width at cab cowl (total width = 2.10 m)
    grille_w = 0.580  # Semi-width at radiator grille shell (total width = 1.16 m)
    hood_top_z_cowl   = 1.940
    hood_top_z_grille = 1.860
    hood_bot_z        = 1.250

    # 1. Butterfly Hood Top Panels (Left and Right halves divided by center hinge)
    # Master cross-sections from Cowl to Grille: 7 stations along length
    stations = 7
    pt_grid_left = []
    pt_grid_right = []

    for i in range(stations):
        t = i / (stations - 1)
        y = y_cowl + t * (y_grille - y_cowl)
        w = cowl_w + t * (grille_w - cowl_w)
        z_top = hood_top_z_cowl + t * (hood_top_z_grille - hood_top_z_cowl)

        # Crown peak in center
        crown_peak = 0.045 * (1.0 - (t * 0.4))

        # 4 lateral points per side: Center peak, Mid-crown, Hood shoulder, Hood side fold
        # Left half (X < 0)
        row_l = [
            Vector(( 0.000, y, z_top + crown_peak)),
            Vector((-w * 0.35, y, z_top + crown_peak * 0.8)),
            Vector((-w * 0.72, y, z_top)),
            Vector((-w * 0.95, y, z_top - 0.080)),
        ]
        # Right half (X > 0)
        row_r = [
            Vector(( 0.000, y, z_top + crown_peak)),
            Vector(( w * 0.35, y, z_top + crown_peak * 0.8)),
            Vector(( w * 0.72, y, z_top)),
            Vector(( w * 0.95, y, z_top - 0.080)),
        ]
        pt_grid_left.append(row_l)
        pt_grid_right.append(row_r)

    make_quad_grid(bm_hood, pt_grid_left)
    make_quad_grid(bm_hood, pt_grid_right)

    # Center Longitudinal Stainless Piano Hinge Extrusion
    p_hinge_cowl   = Vector((0.0, y_cowl - 0.02, hood_top_z_cowl + 0.050))
    p_hinge_grille = Vector((0.0, y_grille + 0.02, hood_top_z_grille + 0.035))
    create_cylinder_between(bm_hood, p_hinge_cowl, p_hinge_grille, radius=0.016, segments=12)

    # Vertical Hood Side Cheeks (Connecting shoulder to lower fender line)
    for side in [1.0, -1.0]:
        cheek_top = []
        cheek_bot = []
        for i in range(stations):
            t = i / (stations - 1)
            y = y_cowl + t * (y_grille - y_cowl)
            w = cowl_w + t * (grille_w - cowl_w)
            z_top = hood_top_z_cowl + t * (hood_top_z_grille - hood_top_z_cowl) - 0.080
            z_bot = hood_bot_z + t * 0.050
            cheek_top.append(Vector((side * w * 0.95, y, z_top)))
            cheek_bot.append(Vector((side * (w * 0.95 + 0.02), y, z_bot)))

        make_quad_strip(bm_hood, cheek_top, cheek_bot)

    # 2. 24 Stamped Side Engine Cooling Louvers per side
    for side in [1.0, -1.0]:
        louver_start_y = 1.650
        louver_end_y   = 2.250
        n_louvers      = 24
        for li in range(n_louvers):
            ly = louver_start_y + (li / (n_louvers - 1)) * (louver_end_y - louver_start_y)
            t_ly = (ly - y_cowl) / (y_grille - y_cowl)
            lw = (cowl_w + t_ly * (grille_w - cowl_w)) * 0.95 + 0.022
            lz = 1.450 + (li % 3) * 0.070

            # 3D Pressed Louver Slat (Punched outwards by 14mm)
            p_lv1 = Vector((side * lw, ly - 0.018, lz))
            p_lv2 = Vector((side * (lw + 0.014), ly, lz + 0.045))
            p_lv3 = Vector((side * lw, ly + 0.018, lz))
            create_oriented_box_between(bm_louvers, p_lv1, p_lv2, width=0.006, height=0.010)
            create_oriented_box_between(bm_louvers, p_lv2, p_lv3, width=0.006, height=0.010)

    # 3. Broad Sweeping Front Fender Wings over Steer Axle
    # Fenders sweep from bumper (Y=+3.75m) up over tire (Y=+2.60m) back to cab steps (Y=+1.55m)
    fender_steps = 16
    for side in [1.0, -1.0]:
        fen_top = []
        fen_lip = []
        fen_inner = []

        for s in range(fender_steps + 1):
            t = s / fender_steps
            # Parametric arch over steer wheel (center Y=2.60, R=0.85)
            theta = math.pi * (0.05 + 0.90 * t)
            fy = 2.600 + 0.950 * math.cos(theta)
            fz = 0.560 + 0.720 * math.sin(theta)
            if fy > 3.700:
                fz = 0.720 - (fy - 3.700) * 0.8
            if fy < 1.700:
                fz = 0.720 - (1.700 - fy) * 0.9

            fx_inner = side * (0.620 + (3.800 - fy) * 0.16)
            fx_outer = side * 1.220

            fen_inner.append(Vector((fx_inner, fy, fz + 0.080)))
            fen_top.append(Vector((fx_outer, fy, fz + 0.060)))
            # Rolled outer lip
            fen_lip.append(Vector((fx_outer + side * 0.025, fy, fz - 0.080)))

        make_quad_strip(bm_fenders, fen_inner, fen_top)
        make_quad_strip(bm_fenders, fen_top, fen_lip)

        # Fender Front Inner Mudguard Splash Wall
        wall_top = fen_inner
        wall_bot = [Vector((p.x, p.y, 0.650)) for p in fen_inner]
        make_quad_strip(bm_fenders, wall_top, wall_bot)

        # 4. Heavy Rubber Hood Hold-Down Dog-Bone Latches (2 per side)
        for latch_y in [2.350, 3.450]:
            t_lat = (latch_y - y_cowl) / (y_grille - y_cowl)
            lat_w = (cowl_w + t_lat * (grille_w - cowl_w)) * 0.95 + 0.025
            lat_z = hood_bot_z + t_lat * 0.050 + 0.040

            # Chrome hood catch bracket
            p_c_top = Vector((side * lat_w, latch_y, lat_z + 0.040))
            p_c_bot = Vector((side * lat_w, latch_y, lat_z))
            create_oriented_box_between(bm_hood, p_c_top, p_c_bot, width=0.025, height=0.035)

            # Molded rubber dog-bone strap
            p_strap_top = p_c_top
            p_strap_bot = Vector((side * (lat_w + 0.035), latch_y, lat_z - 0.090))
            create_cylinder_between(bm_hood, p_strap_top, p_strap_bot, radius=0.010, segments=8)

            # Lower fender cast catch bracket
            create_oriented_box_between(bm_fenders, p_strap_bot, p_strap_bot - Vector((0, 0, 0.03)),
                                        width=0.030, height=0.025)

    obj_hood    = link_obj("BODY_Hood_Butterfly_Panels", bm_hood, parent, mats['body_primary'], bevel=0.003)
    obj_fenders = link_obj("BODY_Front_Fender_Wings", bm_fenders, parent, mats['body_primary'], bevel=0.003)
    obj_louvers = link_obj("BODY_Side_Hood_Louvers", bm_louvers, parent, mats['body_accent'], bevel=0.001)

    return [obj_hood, obj_fenders, obj_louvers]

