    res_bt = bmesh.ops.create_cube(bm_rad, size=1.0)
    bmesh.ops.scale(bm_rad, verts=res_bt['verts'], vec=(rad_w * 1.02, rad_d * 1.15, 0.110))
    bmesh.ops.translate(bm_rad, verts=res_bt['verts'], vec=bot_tank_pos)

    # Brass Drain Cock Petcock on bottom tank
    add_hex_bolt(bm_rad, bot_tank_pos - Vector((0.35, 0, 0.06)),
                 direction=Vector((0, 0, -1)), radius=0.012, height=0.016)

    # 4. Engine Cooling Fan Shroud (Rear of Radiator)
    shroud_pos = Vector((0.0, rad_y - rad_d * 0.55, rad_z))
    res_shroud = bmesh.ops.create_cone(bm_rad, cap_ends=False, segments=24,
                                       radius1=0.420, radius2=0.380, depth=0.140)
    v_sh = res_shroud['verts']
    bmesh.ops.rotate(bm_rad, verts=v_sh, matrix=Matrix.Rotation(math.radians(90.0), 3, 'X'))
    bmesh.ops.translate(bm_rad, verts=v_sh, vec=shroud_pos)

    # Radiator Lower Frame Mounting Tie-Down Brackets & Isolator Bushings
    for side in [1.0, -1.0]:
        p_iso = Vector((side * 0.440, rad_y, bot_tank_pos.z - 0.070))
        create_cylinder_between(bm_rad, p_iso, p_iso - Vector((0, 0, 0.050)), radius=0.045, segments=12)
        add_hex_bolt(bm_rad, p_iso - Vector((0, 0, 0.055)), direction=Vector((0, 0, -1)), radius=0.014, height=0.016)

    return link_obj("CHASSIS_Radiator_Core_And_Shroud", bm_rad, parent, mats['chassis_black'], bevel=0.002)

