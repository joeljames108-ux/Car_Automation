# 19. SUBSYSTEM 16: TYPE 30/30 AIR BRAKE CHAMBERS & S-CAM SLACK ADJUSTERS
# ----------------------------------------------------------------------------
def build_chassis_brake_actuation_system(parent, mats):
    """
    Constructs the heavy pneumatic commercial brake actuation hardware:
    - Type 20 single-diaphragm front air brake chambers on steer axle
    - Type 30/30 dual-diaphragm piggyback spring brake emergency chambers on tandem drive axles
    - Forged S-cam camshaft tubes, camshaft support brackets, and grease zerks
    - Heavy manual slack adjusters with clevis pins, pushrods, and return springs
    - Cast brake spider mounting flanges on all three axles
    """
    bm_chambers = bmesh.new()
    bm_linkage  = bmesh.new()

    # 1. Front Steer Axle Type 20 Service Brake Chambers (Y = +2.600 m)
    front_axle_y = 2.600
    front_axle_z = 0.560
    for side in [1.0, -1.0]:
        sx = side * 0.760
        # Chamber position angled upward behind front axle
        p_fc_in  = Vector((sx, front_axle_y - 0.160, front_axle_z + 0.120))
        p_fc_out = Vector((sx, front_axle_y - 0.260, front_axle_z + 0.150))
        create_cylinder_between(bm_chambers, p_fc_in, p_fc_out, radius=0.085, segments=16)

        # Clamping ring around diaphragm flange
        p_cr_mid = (p_fc_in + p_fc_out) * 0.5
        res_cr = bmesh.ops.create_cone(bm_chambers, cap_ends=True, segments=16,
                                       radius1=0.095, radius2=0.095, depth=0.020)
        v_cr = res_cr['verts']
        rot_q = (p_fc_out - p_fc_in).normalized().to_track_quat('Z', 'Y')
        bmesh.ops.rotate(bm_chambers, verts=v_cr, matrix=rot_q.to_matrix())
        bmesh.ops.translate(bm_chambers, verts=v_cr, vec=p_cr_mid)

        # Pushrod & Clevis to Front Slack Adjuster
        p_rod_start = p_fc_in
        p_rod_end   = Vector((sx, front_axle_y - 0.080, front_axle_z + 0.060))
        create_cylinder_between(bm_linkage, p_rod_start, p_rod_end, radius=0.010, segments=8)

        # Manual Slack Adjuster Arm
        p_cam_end = Vector((sx + side * 0.040, front_axle_y - 0.080, front_axle_z))
        create_oriented_box_between(bm_linkage, p_rod_end, p_cam_end, width=0.035, height=0.120)

        # Clevis Pin & Cotter Key
        add_hex_bolt(bm_linkage, p_rod_end, direction=Vector((1, 0, 0)), radius=0.008, height=0.014)

    # 2. Tandem Rear Axles Type 30/30 Piggyback Spring Brake Chambers (4 Chambers Total)
    tandem_axles = [
        ("Fwd_Tandem",  -2.350),
        ("Rear_Tandem", -3.650),
    ]
    tandem_axle_z = 0.560

    for t_name, ay in tandem_axles:
        for side in [1.0, -1.0]:
            sx = side * 0.750

            # Forward Service Chamber Body
            p_sc_front = Vector((sx, ay + 0.160, tandem_axle_z + 0.080))
            p_sc_rear  = Vector((sx, ay + 0.280, tandem_axle_z + 0.080))
            create_cylinder_between(bm_chambers, p_sc_front, p_sc_rear, radius=0.105, segments=18)

            # Center Flange Clamp
            p_mid_c = (p_sc_front + p_sc_rear) * 0.5
            res_cl = bmesh.ops.create_cone(bm_chambers, cap_ends=True, segments=18,
                                          radius1=0.115, radius2=0.115, depth=0.024)
            v_cl = res_cl['verts']
            bmesh.ops.rotate(bm_chambers, verts=v_cl, matrix=Matrix.Rotation(math.radians(90.0), 3, 'X'))
            bmesh.ops.translate(bm_chambers, verts=v_cl, vec=p_mid_c)

            # Rearward Parking Emergency Spring Canister (Piggyback Section)
            p_pb_rear = Vector((sx, ay + 0.440, tandem_axle_z + 0.080))
            create_cylinder_between(bm_chambers, p_sc_rear, p_pb_rear, radius=0.100, segments=18)

            # Caging Bolt at Rear of Spring Canister (Emergency Release Bolt)
            p_cage1 = p_pb_rear
            p_cage2 = p_pb_rear + Vector((0, 0.080, 0))
            create_cylinder_between(bm_linkage, p_cage1, p_cage2, radius=0.012, segments=8)
            add_hex_bolt(bm_linkage, p_cage2, direction=Vector((0, 1, 0)), radius=0.014, height=0.015)

            # Pushrod and Rear Slack Adjuster Arm
            p_r_rod1 = p_sc_front
            p_r_rod2 = Vector((sx, ay + 0.060, tandem_axle_z))
            create_cylinder_between(bm_linkage, p_r_rod1, p_r_rod2, radius=0.012, segments=8)

            # S-Cam Camshaft Tube across to brake backing plate
            p_cam_in  = p_r_rod2
            p_cam_out = Vector((side * 0.880, ay, tandem_axle_z))
            create_cylinder_between(bm_linkage, p_cam_in, p_cam_out, radius=0.024, segments=12)

            # Heavy Cast Slack Adjuster Arm
            create_oriented_box_between(bm_linkage, p_r_rod2, p_cam_in, width=0.038, height=0.140)

            # Slack adjuster worm gear manual adjustment hex nut
            add_hex_bolt(bm_linkage, p_cam_in + Vector((0, -0.04, 0)),
                         direction=Vector((0, -1, 0)), radius=0.010, height=0.012)

    obj_chambers = link_obj("CHASSIS_Air_Brake_Chambers", bm_chambers, parent, mats['chassis_black'], bevel=0.002)
    obj_linkage  = link_obj("CHASSIS_Brake_Scam_Linkages", bm_linkage, parent, mats['cast_iron'], bevel=0.002)

    return [obj_chambers, obj_linkage]

