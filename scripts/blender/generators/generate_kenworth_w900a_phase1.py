# 16. SUBSYSTEM 13: FULLER ROADRANGER 13-SPEED TRANSMISSION & DRIVELINE
# ----------------------------------------------------------------------------
def build_transmission_casing_and_underbody(parent, mats):
    """
    Constructs the Fuller Roadranger 13-speed transmission casing & drivelines:
    - Ribbed aluminum transmission main case (Y=+0.80m to Y=+1.40m, Z=0.68m)
    - Clutch bellhousing, shift tower base, and dual PTO (power take-off) access covers
    - Spicer 1810 series main driveshaft with universal joints and slip yoke
    - Dual heavy steel driveshaft safety containment loops bolted to crossmembers
    """
    bm_trans = bmesh.new()

    trans_pos = Vector((0.0, 1.150, 0.680))

    # 1. Main Transmission Casing (Ribbed rectangular/cylindrical cast housing)
    res_case = bmesh.ops.create_cube(bm_trans, size=1.0)
    bmesh.ops.scale(bm_trans, verts=res_case['verts'], vec=(0.420, 0.680, 0.380))
