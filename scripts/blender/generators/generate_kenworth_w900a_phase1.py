# 6. SUBSYSTEM 3: EATON 40,000-LB TANDEM REAR DRIVE AXLES & WALKING-BEAM SUSPENSION
# ----------------------------------------------------------------------------
def build_tandem_drive_axles(parent, mats):
    """
    Constructs the Eaton 40,000-lb tandem drive axles & Hendrickson walking-beam suspension:
    - Forward drive axle at Y = -2.350 m, Z = 0.560 m with inter-axle power divider
    - Rearward drive axle at Y = -3.650 m, Z = 0.560 m (1.300 m tandem axle spread)
    - Dual cast iron differential pumpkins with 12 perimeter cover bolts and magnetic drain plugs
    - Hendrickson heavy-duty walking equalizing beams with massive forged trunnion center hub
    - Upper torque radius rods and transverse track bars (Panhard rods)
    """
    bm_drive = bmesh.new()
    bm_bogie = bmesh.new()

    axle_fwd_y  = -2.350
    axle_rear_y = -3.650
    bogie_mid_y = (axle_fwd_y + axle_rear_y) * 0.5  # -3.000 m
    axle_z      =  0.560
    axle_w      =  2.150

    axle_configs = [
        ("Forward", axle_fwd_y, True),
        ("Rearward", axle_rear_y, False),
    ]

    for label, ay, is_fwd in axle_configs:
        # 1. Cast Banjo Axle Tubes (Left and Right)
        p_left_tube  = Vector((-axle_w * 0.5, ay, axle_z))
        p_right_tube = Vector(( axle_w * 0.5, ay, axle_z))
        create_cylinder_between(bm_drive, p_left_tube, p_right_tube, radius=0.065, segments=16)

        # 2. Central Differential Banjo Housing (Pumpkin)
        res_diff = bmesh.ops.create_icosphere(bm_drive, subdivisions=3, radius=0.220)
        v_diff = res_diff['verts']
        bmesh.ops.scale(bm_drive, verts=v_diff, vec=(0.95, 1.25, 1.10))
        bmesh.ops.translate(bm_drive, verts=v_diff, vec=Vector((0.0, ay, axle_z)))

        # Differential Rear Inspection Cover with Bolted Flange
        cover_pos = Vector((0.0, ay - 0.230, axle_z))
        res_cov = bmesh.ops.create_cone(bm_drive, cap_ends=True, segments=20,
                                        radius1=0.170, radius2=0.150, depth=0.060)
        v_cov = res_cov['verts']
        bmesh.ops.rotate(bm_drive, verts=v_cov, matrix=Matrix.Rotation(math.radians(90.0), 3, 'X'))
        bmesh.ops.translate(bm_drive, verts=v_cov, vec=cover_pos)

        # 12 Perimeter Flange Hex Bolts on Differential Cover
        for bi in range(12):
            angle = bi * (2.0 * math.pi / 12)
            bx = 0.155 * math.cos(angle)
            bz = 0.155 * math.sin(angle)
            add_hex_bolt(bm_drive, Vector((bx, ay - 0.262, axle_z + bz)),
                         direction=Vector((0, -1, 0)), radius=0.008, height=0.010)

        # Magnetic Drain Plug at Bottom of Housing
        add_hex_bolt(bm_drive, Vector((0.0, ay, axle_z - 0.225)),
                     direction=Vector((0, 0, -1)), radius=0.014, height=0.012)

        # 3. Inter-Axle Power Divider on Forward Axle
        if is_fwd:
            # Top-mounted cylindrical power divider housing
            pd_pos = Vector((0.0, ay + 0.180, axle_z + 0.090))
            res_pd = bmesh.ops.create_cone(bm_drive, cap_ends=True, segments=16,
                                           radius1=0.110, radius2=0.095, depth=0.220)
            v_pd = res_pd['verts']
            bmesh.ops.rotate(bm_drive, verts=v_pd, matrix=Matrix.Rotation(math.radians(90.0), 3, 'X'))
            bmesh.ops.translate(bm_drive, verts=v_pd, vec=pd_pos)

            # Air-shift lockout cylinder on power divider
            pd_air_p1 = pd_pos + Vector((0.08, -0.05, 0.08))
            pd_air_p2 = pd_air_p1 + Vector((0.0, 0.12, 0.0))
            create_cylinder_between(bm_drive, pd_air_p1, pd_air_p2, radius=0.035, segments=12)

            # Short Inter-Axle Jackshaft / Driveshaft connecting forward and rearward axles
            p_jack_fwd  = Vector((0.0, ay - 0.220, axle_z + 0.060))
            p_jack_rear = Vector((0.0, axle_rear_y + 0.220, axle_z + 0.060))
            create_cylinder_between(bm_drive, p_jack_fwd, p_jack_rear, radius=0.040, segments=14)

            # Universal joint yokes on jackshaft ends
            for jy in [ay - 0.230, axle_rear_y + 0.230]:
                create_oriented_box_between(bm_drive, Vector((-0.06, jy, axle_z + 0.06)),
                                            Vector((0.06, jy, axle_z + 0.06)), width=0.08, height=0.08)

        # 4. Heavy Brake Caliper & 16.5" x 7" Cast Brake Drums (Inner Dual Area)
        for side in [1.0, -1.0]:
            drum_x = side * 0.720
            p_drum_in  = Vector((drum_x, ay, axle_z))
            p_drum_out = Vector((drum_x + side * 0.180, ay, axle_z))
            create_cylinder_between(bm_drive, p_drum_in, p_drum_out, radius=0.230, segments=24)

    # 5. Hendrickson Heavy-Duty Equalizing Walking Beams (Left and Right)
    beam_x_offset = 0.520
    for side in [1.0, -1.0]:
        bx = side * beam_x_offset

        # Forged Central Trunnion Pivot Hub (Mounted to Chassis Center Bogie Crossmember)
        p_trun_in  = Vector((bx - side * 0.060, bogie_mid_y, axle_z + 0.020))
        p_trun_out = Vector((bx + side * 0.060, bogie_mid_y, axle_z + 0.020))
        create_cylinder_between(bm_bogie, p_trun_in, p_trun_out, radius=0.085, segments=18)

        # Center Trunnion Cap with 4 Heavy Clamp Studs
        add_hex_bolt(bm_bogie, Vector((bx + side * 0.065, bogie_mid_y - 0.04, axle_z + 0.06)),
                     direction=Vector((side, 0, 0)), radius=0.012, height=0.012)
        add_hex_bolt(bm_bogie, Vector((bx + side * 0.065, bogie_mid_y + 0.04, axle_z + 0.06)),
                     direction=Vector((side, 0, 0)), radius=0.012, height=0.012)
        add_hex_bolt(bm_bogie, Vector((bx + side * 0.065, bogie_mid_y - 0.04, axle_z - 0.02)),
                     direction=Vector((side, 0, 0)), radius=0.012, height=0.012)
        add_hex_bolt(bm_bogie, Vector((bx + side * 0.065, bogie_mid_y + 0.04, axle_z - 0.02)),
                     direction=Vector((side, 0, 0)), radius=0.012, height=0.012)

        # Forged Walking Beam Arms (Forward and Rearward from Center Trunnion)
        p_center = Vector((bx, bogie_mid_y, axle_z + 0.020))
        p_fwd_axle_mount  = Vector((bx, axle_fwd_y,  axle_z))
        p_rear_axle_mount = Vector((bx, axle_rear_y, axle_z))

        # Forward equalizing arm (Tapered heavy I-beam section)
        create_oriented_box_between(bm_bogie, p_center, p_fwd_axle_mount, width=0.075, height=0.140)
        # Rearward equalizing arm
        create_oriented_box_between(bm_bogie, p_center, p_rear_axle_mount, width=0.075, height=0.140)

        # Rubber End Bushing Pins at Axle Saddle Connections
        for ax_pos in [p_fwd_axle_mount, p_rear_axle_mount]:
            p_pin1 = Vector((bx - side * 0.050, ax_pos.y, ax_pos.z))
            p_pin2 = Vector((bx + side * 0.050, ax_pos.y, ax_pos.z))
            create_cylinder_between(bm_bogie, p_pin1, p_pin2, radius=0.045, segments=14)

        # 6. Upper Torque Radius Rods (Controlling Axle Wrap Under High Braking / Torque)
        for ay_val in [axle_fwd_y, axle_rear_y]:
            p_rod_axle  = Vector((bx, ay_val, axle_z + 0.280))
            p_rod_frame = Vector((bx, bogie_mid_y, axle_z + 0.380))
            create_cylinder_between(bm_bogie, p_rod_axle, p_rod_frame, radius=0.028, segments=12)

            # Spherical rod end eyes
            for ep in [p_rod_axle, p_rod_frame]:
                p_e1 = Vector((bx - 0.035, ep.y, ep.z))
                p_e2 = Vector((bx + 0.035, ep.y, ep.z))
                create_cylinder_between(bm_bogie, p_e1, p_e2, radius=0.038, segments=12)

    # 7. Transverse Panhard Track Bar on Forward Drive Axle (Lateral Stability)
    p_pan_axle  = Vector((-0.300, axle_fwd_y + 0.120, axle_z + 0.180))
    p_pan_frame = Vector(( 0.440, axle_fwd_y + 0.120, axle_z + 0.320))
    create_cylinder_between(bm_bogie, p_pan_axle, p_pan_frame, radius=0.024, segments=12)

    obj_drive = link_obj("CHASSIS_Tandem_Rear_Eaton_Drive_Axles", bm_drive, parent, mats['cast_iron'], bevel=0.003)
    obj_bogie = link_obj("CHASSIS_Tandem_Rear_Hendrickson_Bogie", bm_bogie, parent, mats['chassis_black'], bevel=0.003)

    return [obj_drive, obj_bogie]

