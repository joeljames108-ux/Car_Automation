# 5. SUBSYSTEM 2: ROCKWELL DROP-FORGED I-BEAM FRONT STEER AXLE & SPRINGS
# ----------------------------------------------------------------------------
def build_front_axle_and_steering(parent, mats):
    """
    Constructs the Rockwell 12,000-lb drop-forged I-beam front axle assembly:
    - Center drop-forged I-beam with forged kingpin bosses (Y=+2.600m, Z=0.560m)
    - 10-leaf semi-elliptical heavy spring packs with U-bolts and cast rebound clips
    - Front spring front fixed pin hangers and rear swinging shackles with grease zerks
    - Cast steering knuckles, kingpins, steering arms, tie-rod, and hydraulic drag link
    - Heavy double-acting telescoping front shock absorbers with lower axle mounts
    """
    bm_axle = bmesh.new()
    bm_susp = bmesh.new()

    axle_y = 2.600
    axle_z = 0.560
    track_w = 2.080
    kingpin_x = 0.940

    # 1. Rockwell Drop-Forged I-Beam Center Section
    p_center_left  = Vector((-0.650, axle_y, axle_z - 0.070))
    p_center_right = Vector(( 0.650, axle_y, axle_z - 0.070))
    create_oriented_box_between(bm_axle, p_center_left, p_center_right, width=0.075, height=0.110)

    # Upper and lower I-beam flange extensions for Class-A structural realism
    for df_z in [-0.055, 0.055]:
        p_fl_l = Vector((-0.650, axle_y, axle_z - 0.070 + df_z))
        p_fl_r = Vector(( 0.650, axle_y, axle_z - 0.070 + df_z))
        create_oriented_box_between(bm_axle, p_fl_l, p_fl_r, width=0.105, height=0.022)

    # Forged Upward Sweeps to Kingpin Bosses
    for side in [1.0, -1.0]:
        p_sweep_in  = Vector((side * 0.650, axle_y, axle_z - 0.070))
        p_sweep_out = Vector((side * kingpin_x, axle_y, axle_z))
        create_oriented_box_between(bm_axle, p_sweep_in, p_sweep_out, width=0.085, height=0.100)

        # Vertical Kingpin Cylindrical Bosses
        p_kp_top = Vector((side * kingpin_x, axle_y, axle_z + 0.120))
        p_kp_bot = Vector((side * kingpin_x, axle_y, axle_z - 0.120))
        create_cylinder_between(bm_axle, p_kp_top, p_kp_bot, radius=0.048, segments=16)

        # Kingpin grease caps top and bottom
        for kp_end in [p_kp_top, p_kp_bot]:
            add_hex_bolt(bm_axle, kp_end, direction=Vector((0, 0, 1 if kp_end.z > axle_z else -1)),
                         radius=0.016, height=0.012)

        # Cast Wheel Spindle Stub Axle (Projecting outwards into wheel hub)
        p_spindle_in  = Vector((side * kingpin_x, axle_y, axle_z))
        p_spindle_out = Vector((side * (track_w * 0.5 - 0.05), axle_y, axle_z))
        create_cylinder_between(bm_axle, p_spindle_in, p_spindle_out, radius=0.038, segments=16)

        # Brake Backing Dust Shield (Large 16.5-inch diameter circular plate)
        p_dust_in  = Vector((side * (track_w * 0.5 - 0.070), axle_y, axle_z))
        p_dust_out = Vector((side * (track_w * 0.5 - 0.076), axle_y, axle_z))
        create_cylinder_between(bm_axle, p_dust_in, p_dust_out, radius=0.220, segments=24)

    # 2. Semi-Elliptical Multi-Leaf Spring Packs (10 progressive leaves per side)
    spring_center_x = 0.470
    spring_span     = 1.350
    leaf_thickness  = 0.011
    leaf_width      = 0.095

    for side in [1.0, -1.0]:
        sx = side * spring_center_x

        # 10 individual leaves of decreasing lengths for true CAD realism
        for leaf_idx in range(10):
            frac = 1.0 - (leaf_idx * 0.08)
            current_span = spring_span * frac
            lz = axle_z + 0.045 + (leaf_idx * leaf_thickness)

            # Curved spring profile
            pts_top = []
            pts_bot = []
            segments = 12
            for s in range(segments + 1):
                t = s / segments
                sy = axle_y - (current_span * 0.5) + (t * current_span)
                camber = -math.sin(t * math.pi) * (0.045 * frac)
                pts_top.append(Vector((sx - leaf_width * 0.5, sy, lz + camber + leaf_thickness)))
                pts_bot.append(Vector((sx + leaf_width * 0.5, sy, lz + camber)))

            # Extruded leaf strip
            for seg in range(segments):
                p1 = Vector((sx, pts_top[seg].y, pts_top[seg].z))
                p2 = Vector((sx, pts_top[seg+1].y, pts_top[seg+1].z))
                create_oriented_box_between(bm_susp, p1, p2, width=leaf_width, height=leaf_thickness)

        # Spring Eyes on Top Main Leaf
        p_eye_front = Vector((sx, axle_y + spring_span * 0.5, axle_z + 0.080))
        p_eye_rear  = Vector((sx, axle_y - spring_span * 0.5, axle_z + 0.080))
        for eye_p in [p_eye_front, p_eye_rear]:
            p_e1 = Vector((sx - 0.055, eye_p.y, eye_p.z))
            p_e2 = Vector((sx + 0.055, eye_p.y, eye_p.z))
            create_cylinder_between(bm_susp, p_e1, p_e2, radius=0.028, segments=12)

        # Cast Frame Spring Hangers
        # Front fixed hanger
        res_h_front = bmesh.ops.create_cube(bm_susp, size=1.0)
        bmesh.ops.scale(bm_susp, verts=res_h_front['verts'], vec=(0.080, 0.120, 0.180))
        bmesh.ops.translate(bm_susp, verts=res_h_front['verts'], vec=p_eye_front + Vector((0, 0.03, 0.08)))

        # Rear swinging shackle bracket and dual shackle link plates
        for sh_x in [-0.050, 0.050]:
            p_sh_top = Vector((sx + sh_x, p_eye_rear.y - 0.04, axle_z + 0.200))
            p_sh_bot = Vector((sx + sh_x, p_eye_rear.y,        p_eye_rear.z))
            create_oriented_box_between(bm_susp, p_sh_top, p_sh_bot, width=0.016, height=0.045)
            add_hex_bolt(bm_susp, p_sh_top, direction=Vector((1, 0, 0)), radius=0.010, height=0.010)
            add_hex_bolt(bm_susp, p_sh_bot, direction=Vector((1, 0, 0)), radius=0.010, height=0.010)

        # Dual Heavy Square U-Bolts clamping spring pack to axle pad
        for dy_u in [-0.080, 0.080]:
            # U-bolt crossbar top
            p_ub_tl = Vector((sx - 0.060, axle_y + dy_u, axle_z + 0.170))
            p_ub_tr = Vector((sx + 0.060, axle_y + dy_u, axle_z + 0.170))
            create_cylinder_between(bm_susp, p_ub_tl, p_ub_tr, radius=0.011, segments=10)

            # U-bolt vertical legs
            p_ub_bl = Vector((sx - 0.060, axle_y + dy_u, axle_z - 0.090))
            p_ub_br = Vector((sx + 0.060, axle_y + dy_u, axle_z - 0.090))
            create_cylinder_between(bm_susp, p_ub_tl, p_ub_bl, radius=0.011, segments=10)
            create_cylinder_between(bm_susp, p_ub_tr, p_ub_br, radius=0.011, segments=10)

            # Lower U-bolt retention nuts
            add_hex_bolt(bm_susp, p_ub_bl, direction=Vector((0, 0, -1)), radius=0.013, height=0.014)
            add_hex_bolt(bm_susp, p_ub_br, direction=Vector((0, 0, -1)), radius=0.013, height=0.014)

        # Spring Rebound Clips (Holding leaves together)
        for clip_y in [axle_y - 0.35, axle_y + 0.35]:
            p_cl1 = Vector((sx - 0.055, clip_y, axle_z + 0.04))
            p_cl2 = Vector((sx + 0.055, clip_y, axle_z + 0.04))
            create_oriented_box_between(bm_susp, p_cl1, p_cl2, width=0.020, height=0.100)

        # Double-Acting Telescoping Hydraulic Front Shock Absorber
        p_shock_axle  = Vector((sx + side * 0.075, axle_y, axle_z + 0.020))
        p_shock_frame = Vector((sx + side * 0.045, axle_y + 0.080, axle_z + 0.340))
        # Lower main body tube
        p_shock_mid = (p_shock_axle + p_shock_frame) * 0.5
        create_cylinder_between(bm_susp, p_shock_axle, p_shock_mid, radius=0.035, segments=12)
        # Upper dust shield shroud
        create_cylinder_between(bm_susp, p_shock_mid, p_shock_frame, radius=0.042, segments=12)

    # 3. Heavy Cross-Chassis Steering Tie-Rod Assembly
    p_tierod_left  = Vector((-kingpin_x + 0.05, axle_y - 0.160, axle_z - 0.030))
    p_tierod_right = Vector(( kingpin_x - 0.05, axle_y - 0.160, axle_z - 0.030))
    create_cylinder_between(bm_susp, p_tierod_left, p_tierod_right, radius=0.025, segments=14)

    # Tie rod threaded ends and adjustment clamps
    for side in [1.0, -1.0]:
        clamp_p1 = Vector((side * (kingpin_x - 0.14), axle_y - 0.160, axle_z - 0.030))
        clamp_p2 = Vector((side * (kingpin_x - 0.06), axle_y - 0.160, axle_z - 0.030))
        create_cylinder_between(bm_susp, clamp_p1, clamp_p2, radius=0.032, segments=12)
        add_hex_bolt(bm_susp, clamp_p1 + Vector((0, 0.03, 0)), direction=Vector((0, 1, 0)), radius=0.008, height=0.015)

    # Hydraulic Steering Drag Link (From driver frame rail steering box down to left knuckle)
    p_drag_box = Vector((-0.510, 2.250, 0.820))
    p_drag_arm = Vector((-kingpin_x + 0.04, 2.500, axle_z + 0.040))
    create_cylinder_between(bm_susp, p_drag_box, p_drag_arm, radius=0.022, segments=12)

    # Pitman Arm from Steering Gear
    p_pitman_top = Vector((-0.520, 2.250, 0.900))
    create_oriented_box_between(bm_susp, p_pitman_top, p_drag_box, width=0.035, height=0.045)

    obj_axle = link_obj("CHASSIS_Front_Rockwell_IBeam_Axle", bm_axle, parent, mats['cast_iron'], bevel=0.003)
    obj_susp = link_obj("CHASSIS_Front_Leaf_Springs_And_Steering", bm_susp, parent, mats['chassis_black'], bevel=0.002)

    return [obj_axle, obj_susp]

