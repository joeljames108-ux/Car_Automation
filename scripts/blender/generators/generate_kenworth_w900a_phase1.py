    bmesh.ops.scale(bm_plumb, verts=res_lube['verts'], vec=(0.035, 0.160, 0.070))
    bmesh.ops.translate(bm_plumb, verts=res_lube['verts'], vec=lube_pos)

    # 6 Grease Zerk Fittings on Manifold Block
    for zi in range(6):
        zy = lube_pos.y - 0.065 + zi * 0.026
        z_pos = Vector((lube_pos.x - 0.022, zy, lube_pos.z))
        create_cylinder_between(bm_plumb, z_pos, z_pos - Vector((0.018, 0, 0)), radius=0.005, segments=6)

    # 4. Trailer Air Supply Gladhand Bulkhead Support Plate (Behind Cab Sleeper)
    bulkhead_pos = Vector((0.000, -1.020, 1.150))
    res_bh = bmesh.ops.create_cube(bm_plumb, size=1.0)
    bmesh.ops.scale(bm_plumb, verts=res_bh['verts'], vec=(0.320, 0.015, 0.120))
    bmesh.ops.translate(bm_plumb, verts=res_bh['verts'], vec=bulkhead_pos)

    # Dual Service (Blue) & Emergency (Red) Trailer Bulkhead Couplings
    for gx in [-0.08, 0.08]:
        p_gh1 = Vector((gx, -1.020, 1.150))
        p_gh2 = Vector((gx, -1.070, 1.150))
        create_cylinder_between(bm_plumb, p_gh1, p_gh2, radius=0.022, segments=12)

    return link_obj("CHASSIS_Plumbing_Valves_And_Lubrication", bm_plumb, parent, mats['chassis_black'], bevel=0.002)

