        p_ph1 = Vector((door_x + side * 0.004, door_y - 0.280, door_z - 0.210))
        p_ph2 = Vector((door_x + side * 0.004, door_y + 0.280, door_z - 0.210))
        create_cylinder_between(bm_doors, p_ph1, p_ph2, radius=0.008, segments=8)

