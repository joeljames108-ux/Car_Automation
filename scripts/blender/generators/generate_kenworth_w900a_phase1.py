# 12. SUBSYSTEM 9: DUAL 120-GALLON CYLINDRICAL POLISHED ALUMINUM FUEL TANKS
# ----------------------------------------------------------------------------
def build_fuel_tanks_and_battery_boxes(parent, mats):
    """
    Constructs the massive dual cylindrical fuel tanks & battery step boxes:
    - Dual 120-gallon tanks: 26-inch (0.66m) diameter x 65-inch (1.65m) length
    - Spun domed end caps, welded seams, and heavy cast mounting saddles
    - Stainless steel retention T-straps with rubber cushion liners and draw bolts
    - Integrated aluminum diamond-plate top step treads and lower drop stirrup steps
    - Heavy brass fuel filler necks with vented quarter-turn caps and safety chains
    - Aluminum diamond-plate battery and tool boxes with hinged step lids
    """
    bm_tanks = bmesh.new()
    bm_steps = bmesh.new()

    tank_dia = 0.660
    tank_len = 1.650
    tank_y   = 0.250   # Under cab door flanks
    tank_z   = 0.720
    tank_x   = 0.880

    for side in [1.0, -1.0]:
        tx = side * tank_x
        center_pos = Vector((tx, tank_y, tank_z))

        # 1. Main Cylindrical Tank Body
        res_t = bmesh.ops.create_cone(bm_tanks, cap_ends=True, segments=28,
                                      radius1=tank_dia * 0.5, radius2=tank_dia * 0.5, depth=tank_len)
        v_t = res_t['verts']
        bmesh.ops.rotate(bm_tanks, verts=v_t, matrix=Matrix.Rotation(math.radians(90.0), 3, 'X'))
        bmesh.ops.translate(bm_tanks, verts=v_t, vec=center_pos)

        # Spun Domed End Caps (Front and Rear of Tank)
        for dy in [tank_len * 0.5, -tank_len * 0.5]:
            res_dome = bmesh.ops.create_icosphere(bm_tanks, subdivisions=2, radius=tank_dia * 0.5)
            v_dome = res_dome['verts']
            bmesh.ops.scale(bm_tanks, verts=v_dome, vec=(1.0, 0.28, 1.0))
            bmesh.ops.translate(bm_tanks, verts=v_dome, vec=center_pos + Vector((0, dy, 0)))

        # 2. Heavy Stamped Chassis Mounting Saddles & Stainless T-Straps (2 per tank)
        for strap_dy in [-0.520, 0.520]:
            strap_y = tank_y + strap_dy

            # Cast saddle bracket welded to frame rail
            p_sad_in  = Vector((side * 0.470, strap_y, tank_z - 0.05))
            p_sad_out = Vector((tx, strap_y, tank_z - tank_dia * 0.5))
            create_oriented_box_between(bm_steps, p_sad_in, p_sad_out, width=0.065, height=0.080)

            # Stainless steel strap encircling tank
            p_st1 = Vector((tx - side * 0.01, strap_y, tank_z))
            # Ring torus representation
            res_strap = bmesh.ops.create_cone(bm_steps, cap_ends=False, segments=24,
                                              radius1=tank_dia * 0.51, radius2=tank_dia * 0.51, depth=0.045)
            v_str = res_strap['verts']
            bmesh.ops.rotate(bm_steps, verts=v_str, matrix=Matrix.Rotation(math.radians(90.0), 3, 'X'))
            bmesh.ops.translate(bm_steps, verts=v_str, vec=Vector((tx, strap_y, tank_z)))

            # Threaded T-bolt tensioner block at top of strap
            add_hex_bolt(bm_steps, Vector((tx, strap_y, tank_z + tank_dia * 0.51)),
                         direction=Vector((0, 0, 1)), radius=0.012, height=0.018)

        # 3. Cast Brass Fuel Filler Neck & Quarter-Turn Vented Cap
        filler_pos = center_pos + Vector((side * (tank_dia * 0.44), -0.450, tank_dia * 0.35))
        p_fn1 = filler_pos
        p_fn2 = filler_pos + Vector((side * 0.065, 0, 0.065))
        create_cylinder_between(bm_tanks, p_fn1, p_fn2, radius=0.045, segments=14)

        # Chrome Fuel Cap with Serrated Grip Edges
        res_cap = bmesh.ops.create_cone(bm_tanks, cap_ends=True, segments=16,
                                        radius1=0.055, radius2=0.055, depth=0.025)
        v_cap = res_cap['verts']
        rot_quat = Vector((side * 0.707, 0, 0.707)).to_track_quat('Z', 'Y')
        bmesh.ops.rotate(bm_tanks, verts=v_cap, matrix=rot_quat.to_matrix())
        bmesh.ops.translate(bm_tanks, verts=v_cap, vec=p_fn2)

        # 4. Aluminum Diamond-Plate Top Step Tread (Upper Entry Step)
        step_top_pos = center_pos + Vector((side * 0.05, 0.15, tank_dia * 0.505))
        res_st = bmesh.ops.create_cube(bm_steps, size=1.0)
        bmesh.ops.scale(bm_steps, verts=res_st['verts'], vec=(0.240, 0.750, 0.025))
        bmesh.ops.translate(bm_steps, verts=res_st['verts'], vec=step_top_pos)

        # Lower Drop Stirrup Step (Serrated Grip Rung for Easy Cab Ingress)
        p_stirrup_l = center_pos + Vector((side * (tank_dia * 0.48), -0.150, -0.080))
        p_stirrup_r = center_pos + Vector((side * (tank_dia * 0.48),  0.450, -0.080))
        create_oriented_box_between(bm_steps, p_stirrup_l, p_stirrup_r, width=0.090, height=0.022)

        # Stirrup vertical support struts
        for s_pos in [p_stirrup_l, p_stirrup_r]:
            p_strut_top = Vector((s_pos.x - side * 0.06, s_pos.y, tank_z + 0.15))
            create_cylinder_between(bm_steps, p_strut_top, s_pos, radius=0.012, segments=8)

        # 5. Battery & Tool Box Module (Mounted ahead of fuel tank on chassis flank)
        box_pos = Vector((side * 0.820, 1.550, 0.760))
        res_box = bmesh.ops.create_cube(bm_steps, size=1.0)
        bmesh.ops.scale(bm_steps, verts=res_box['verts'], vec=(0.380, 0.580, 0.360))
        bmesh.ops.translate(bm_steps, verts=res_box['verts'], vec=box_pos)

        # Diamond-Plate Hinged Step Lid
        lid_pos = box_pos + Vector((0, 0, 0.190))
        res_lid = bmesh.ops.create_cube(bm_steps, size=1.0)
        bmesh.ops.scale(bm_steps, verts=res_lid['verts'], vec=(0.400, 0.600, 0.030))
        bmesh.ops.translate(bm_steps, verts=res_lid['verts'], vec=lid_pos)

        # Dual T-Handle Latches on Battery Box Lid
        for dly in [-0.18, 0.18]:
            l_pos = lid_pos + Vector((side * 0.205, dly, 0.0))
            add_hex_bolt(bm_steps, l_pos, direction=Vector((side, 0, 0)), radius=0.010, height=0.015)

    obj_tanks = link_obj("HARDWARE_Dual_120Gal_Fuel_Tanks", bm_tanks, parent, mats['polished_aluminum'], bevel=0.003)
    obj_steps = link_obj("HARDWARE_Fuel_Tank_Steps_And_Battery_Boxes", bm_steps, parent, mats['polished_aluminum'], bevel=0.002)

    return [obj_tanks, obj_steps]

