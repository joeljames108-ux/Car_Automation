def build_ladder_chassis_frame(parent, mats):
    """
    Constructs the full 8.1-meter heavy-duty C-channel ladder chassis:
    - Dual longitudinal C-channel frame rails (web height 260mm, flange width 88mm, thickness 12mm)
    - Front bumper horn brackets and frame extension horn horns
    - 6 stamped structural crossmembers with flanged lightening holes & gusset plates
    - Fifth-wheel mounting subframe deck angles and slider base rail supports
    - Full chassis web bolt arrays (over 80 individual Grade-8 structural fasteners)
    """
    bm_rails = bmesh.new()
    bm_cross = bmesh.new()
    bm_gussets = bmesh.new()

    # Frame geometry parameters
    y_front =  3.800
    y_rear  = -4.300
    rail_w  =  0.088
    rail_h  =  0.260
    rail_x_out = 0.470
    rail_x_in  = rail_x_out - rail_w
    top_z   =  0.920
    bot_z   =  top_z - rail_h

    for side in [1.0, -1.0]:
        sx_out = side * rail_x_out
        sx_in  = side * rail_x_in

        # Top Flange Strip
        top_outer = [Vector((sx_out, y_front, top_z)), Vector((sx_out, y_rear, top_z))]
        top_inner = [Vector((sx_in,  y_front, top_z)), Vector((sx_in,  y_rear, top_z))]
        make_quad_strip(bm_rails, top_outer, top_inner)

        # Vertical Web Plate
        web_top = [Vector((sx_out, y_front, top_z)), Vector((sx_out, y_rear, top_z))]
        web_bot = [Vector((sx_out, y_front, bot_z)), Vector((sx_out, y_rear, bot_z))]
        make_quad_strip(bm_rails, web_top, web_bot)

        # Bottom Flange Strip
        bot_outer = [Vector((sx_out, y_front, bot_z)), Vector((sx_out, y_rear, bot_z))]
        bot_inner = [Vector((sx_in,  y_front, bot_z)), Vector((sx_in,  y_rear, bot_z))]
        make_quad_strip(bm_rails, bot_outer, bot_inner)

        # Web Flange Hex Bolts along frame rails (Every 200mm along chassis length)
        for bolt_y_idx in range(40):
            by = y_front - 0.15 - bolt_y_idx * 0.20
            if by > y_rear + 0.10:
                p_b1 = Vector((sx_out + side * 0.005, by, top_z - 0.045))
                p_b2 = Vector((sx_out + side * 0.005, by, bot_z + 0.045))
                for bp in [p_b1, p_b2]:
                    add_hex_bolt(bm_rails, bp, direction=Vector((side, 0, 0)), radius=0.009, height=0.008)

        # Front Bumper Horn Extension Casting (Heavy-duty boxed front bracket)
        horn_p1 = Vector((sx_out, 3.650, 0.780))
        horn_p2 = Vector((sx_out, 3.820, 0.680))
        create_oriented_box_between(bm_rails, horn_p1, horn_p2, width=0.065, height=0.180)

        # Front Tow Pin Boss Sleeve
        res_tow = bmesh.ops.create_cone(bm_rails, cap_ends=True, segments=12,
                                        radius1=0.024, radius2=0.024, depth=0.140)
        v_tow = res_tow['verts']
        bmesh.ops.rotate(bm_rails, verts=v_tow, matrix=Matrix.Rotation(math.radians(90.0), 3, 'X'))
        bmesh.ops.translate(bm_rails, verts=v_tow, vec=Vector((sx_out, 3.810, 0.620)))

        # Rear Frame 45-Degree Snip Angle (Classic heavy highway tractor rear cutoff)
        p_cut_top = Vector((sx_out, y_rear, top_z))
        p_cut_bot = Vector((sx_out, y_rear + 0.180, bot_z))
        create_oriented_box_between(bm_rails, p_cut_top, p_cut_bot, width=0.025, height=0.035)

        # Fifth Wheel Slide Base Support Angle Iron (L-brackets running above tandem bogie)
        fw_angle_p1 = Vector((sx_out + side * 0.020, -1.800, top_z + 0.015))
        fw_angle_p2 = Vector((sx_out + side * 0.020, -3.900, top_z + 0.015))
        create_oriented_box_between(bm_rails, fw_angle_p1, fw_angle_p2, width=0.045, height=0.045)

        # Slide bracket mounting bolts (12 bolts per side along fifth-wheel angle)
        for fwb_i in range(12):
            fwb_y = -1.900 - fwb_i * 0.170
            add_hex_bolt(bm_rails, Vector((sx_out + side * 0.045, fwb_y, top_z + 0.015)),
                         direction=Vector((side, 0, 0)), radius=0.008, height=0.008)

    # 6 Heavy Stamped Structural Crossmembers
    # Positions: Radiator front, Transmission rear, Cab rear mount, Center bogie, Tandem front, Tandem rear
    crossmember_positions = [
        ("Front_Radiator_Crossmember",        3.650, 0.760, 0.180, 0.080, True),
        ("Engine_Rear_Crossmember",           1.850, 0.740, 0.160, 0.075, False),
        ("Cab_Mount_Center_Crossmember",      0.150, 0.760, 0.180, 0.080, True),
        ("Forward_Tandem_Crossmember",       -1.750, 0.780, 0.200, 0.090, True),
        ("Center_Bogie_Trunnion_Crossmember",-3.000, 0.750, 0.220, 0.100, True),
        ("Rear_Tail_Crossmember",            -4.250, 0.820, 0.180, 0.080, False),
    ]

    for cm_name, cm_y, cm_z, cm_h, cm_w, has_holes in crossmember_positions:
        # Crossmember channel beam connecting left and right frame inner faces
        p_left  = Vector((-rail_x_in, cm_y, cm_z))
        p_right = Vector(( rail_x_in, cm_y, cm_z))
        create_oriented_box_between(bm_cross, p_left, p_right, width=cm_w, height=cm_h)

        # Flanged lightening holes on larger structural crossmembers
        if has_holes:
            for hole_x in [-0.22, 0.0, 0.22]:
                hole_p1 = Vector((hole_x, cm_y - cm_w * 0.55, cm_z))
                hole_p2 = Vector((hole_x, cm_y + cm_w * 0.55, cm_z))
                create_cylinder_between(bm_cross, hole_p1, hole_p2, radius=0.040, segments=12)

        # End Gusset Attachment Plates (Connecting crossmember to frame web)
        for g_side in [1.0, -1.0]:
            gx = g_side * rail_x_in
            # Triangular/flanged gusset plate
            g_p1 = Vector((gx, cm_y - 0.090, cm_z - cm_h * 0.5))
            g_p2 = Vector((gx, cm_y + 0.090, cm_z + cm_h * 0.5))
            create_oriented_box_between(bm_gussets, g_p1, g_p2, width=0.018, height=0.040)

            # Gusset 4-bolt pattern
            for dgy in [-0.05, 0.05]:
                for dgz in [-0.04, 0.04]:
                    add_hex_bolt(bm_gussets, Vector((gx - g_side * 0.008, cm_y + dgy, cm_z + dgz)),
                                 direction=Vector((-g_side, 0, 0)), radius=0.007, height=0.007)

    obj_rails = link_obj("CHASSIS_Frame_Rails", bm_rails, parent, mats['chassis_black'], bevel=0.003)
    obj_cross = link_obj("CHASSIS_Crossmembers", bm_cross, parent, mats['chassis_black'], bevel=0.003)
    obj_gussets = link_obj("CHASSIS_Gussets_And_Brackets", bm_gussets, parent, mats['chassis_black'], bevel=0.002)

    return [obj_rails, obj_cross, obj_gussets]

