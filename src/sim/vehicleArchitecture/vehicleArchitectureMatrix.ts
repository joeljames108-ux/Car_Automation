/**
 * Retrieves the specific matrix entry for an architecture and era.
 * Gracefully falls back to normalized IDs if unknown strings are provided.
 */
export function getMatrixEntry(
  architectureId: string | undefined | null,
  eraId: string | undefined | null
): VehicleArchitectureEraEntry {
  const normArch = normalizeArchitectureId(architectureId);
  const normEra = normalizeEraId(eraId);

  const archEntries = VEHICLE_ARCHITECTURE_MATRIX[normArch];
  if (archEntries && archEntries[normEra]) {
    return archEntries[normEra];
  }

  // Fallback to 2020s sedan if somehow unavailable
  return VEHICLE_ARCHITECTURE_MATRIX.sedan["2020s"];
}

/**
 * Retrieves all 7 era entries for a specific architecture.
 */
export function getArchitectureEras(architectureId: string | undefined | null): VehicleArchitectureEraEntry[] {
  const normArch = normalizeArchitectureId(architectureId);
  const archEntries = VEHICLE_ARCHITECTURE_MATRIX[normArch];
  return CANONICAL_ERA_IDS.map((era) => archEntries[era]);
}

/**
 * Retrieves all 24 architecture metadata definitions.
 */
export function getAllArchitectures(): VehicleArchitectureMetadataDefinition[] {
  return CANONICAL_ARCHITECTURE_IDS.map((id) => VEHICLE_ARCHITECTURE_DEFINITIONS[id]);
}

/**
 * Retrieves all 7 era metadata definitions in chronological order.
 */
export function getAllEras(): VehicleEraMetadata[] {
  return CANONICAL_ERA_IDS.map((id) => VEHICLE_ERAS[id]);
}

/**
 * Filters architectures by category group.
 */
export function getArchitecturesByGroup(
  group: "all" | "passenger" | "performance" | "utility" | "commercial" | "motorsport"
): VehicleArchitectureMetadataDefinition[] {
  const all = getAllArchitectures();
  if (group === "all") return all;
  return all.filter((a) => a.categoryGroup === group);
}

/**
 * Searches across all 168 entries by name, reference vehicle, or key design features.
 */
export function searchMatrix(query: string): VehicleArchitectureEraEntry[] {
  if (!query || !query.trim()) return [];
  const q = query.trim().toLowerCase();

  const results: VehicleArchitectureEraEntry[] = [];
  for (const archId of CANONICAL_ARCHITECTURE_IDS) {
    for (const eraId of CANONICAL_ERA_IDS) {
      const entry = VEHICLE_ARCHITECTURE_MATRIX[archId][eraId];
      if (
        entry.referenceVehicle.toLowerCase().includes(q) ||
        entry.architectureId.toLowerCase().includes(q) ||
        entry.designDna.silhouette.toLowerCase().includes(q) ||
        entry.designDna.stylingLanguage.toLowerCase().includes(q) ||
        entry.designDna.keyFeatures.some((f) => f.toLowerCase().includes(q))
      ) {
        results.push(entry);
      }
    }
  }
  return results;
}

/**
 * Checks if a bespoke GLB asset is marked available, or if fallback should be used.
 */
export function checkGlbAvailability(
  architectureId: string | undefined | null,
  eraId: string | undefined | null
): boolean {
  const entry = getMatrixEntry(architectureId, eraId);
  return entry.isGlbAvailable;
}
